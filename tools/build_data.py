"""Build-time helper: openings book trie + piece sprite CSS + app icons.

Run:  python tools/build_data.py
Requires only the Python standard library.
"""
import json
import os
import re
import struct
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
ASSETS = os.path.join(ROOT, "assets")


# --------------------------------------------------------------------------
# 1. Opening book: nested trie keyed by SAN moves.
# --------------------------------------------------------------------------
def build_openings():
    trie = {}
    count = 0
    for letter in "abcde":
        path = os.path.join(DATA, letter + ".tsv")
        with open(path, "r", encoding="utf-8") as fh:
            header = fh.readline()
            for line in fh:
                parts = line.rstrip("\n").split("\t")
                if len(parts) < 3:
                    continue
                eco, name, pgn = parts[0], parts[1], parts[2]
                moves = []
                for tok in pgn.split():
                    tok = re.sub(r"^\d+\.+", "", tok)
                    if not tok or tok[0] in "$" or tok in ("1-0", "0-1", "1/2-1/2", "*"):
                        continue
                    moves.append(tok)
                if not moves or len(moves) > 24:
                    continue
                node = trie
                for mv in moves:
                    node = node.setdefault(mv, {})
                # keep the shortest / most canonical name for a node
                if "n" not in node:
                    node["n"] = name
                    node["e"] = eco
                count += 1
    out = os.path.join(DATA, "openings.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(trie, fh, ensure_ascii=False, separators=(",", ":"))
    print(f"openings: {count} lines -> {os.path.getsize(out)/1024:.0f} KiB")


# --------------------------------------------------------------------------
# 2. Piece sprite CSS (data-URI backgrounds, fully offline).
# --------------------------------------------------------------------------
def build_pieces():
    order = ["wK", "wQ", "wR", "wB", "wN", "wP", "bK", "bQ", "bR", "bB", "bN", "bP"]
    css = ["/* generated by tools/build_data.py - Cburnett pieces (CC BY-SA 3.0) */"]
    for name in order:
        with open(os.path.join(ASSETS, "pieces", name + ".svg"), "r", encoding="utf-8") as fh:
            svg = fh.read()
        svg = re.sub(r'\sstyle="color-scheme:light only"', "", svg)
        svg = re.sub(r'\swidth="45"\sheight="45"', "", svg)
        svg = " ".join(svg.split())
        uri = "data:image/svg+xml," + (
            svg.replace("%", "%25")
            .replace("#", "%23")
            .replace("<", "%3C")
            .replace(">", "%3E")
            .replace('"', "%22")
        )
        css.append(".pc-%s{background-image:url(\"%s\")}" % (name, uri))
    with open(os.path.join(ROOT, "css", "pieces.css"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(css) + "\n")
    print("pieces.css written")


# --------------------------------------------------------------------------
# 3. PNG icons (pure stdlib) - rounded dark tile + board + pawn.
# --------------------------------------------------------------------------
class Canvas:
    def __init__(self, size, bg):
        self.size = size
        self.px = [[bg for _ in range(size)] for _ in range(size)]

    def set(self, x, y, color):
        if 0 <= x < self.size and 0 <= y < self.size:
            self.px[y][x] = color

    def save(self, path):
        raw = bytearray()
        for row in self.px:
            raw.append(0)
            for r, g, b in row:
                raw += bytes((r, g, b))
        def chunk(tag, data):
            out = struct.pack(">I", len(data)) + tag + data
            return out + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        png = b"\x89PNG\r\n\x1a\n"
        png += chunk(b"IHDR", struct.pack(">IIBBBBB", self.size, self.size, 8, 2, 0, 0, 0))
        png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        png += chunk(b"IEND", b"")
        with open(path, "wb") as fh:
            fh.write(png)


def rounded_rect(x, y, w, h, r):
    if x < 0 or y < 0 or x > w or y > h:
        return False
    cx = min(max(x, r), w - r)
    cy = min(max(y, r), h - r)
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def in_poly(x, y, pts):
    inside = False
    n = len(pts)
    j = n - 1
    for i in range(n):
        xi, yi = pts[i]
        xj, yj = pts[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi + 1e-12) + xi:
            inside = not inside
        j = i
    return inside


def make_icon(size, maskable=False):
    bg = (38, 36, 33)
    light = (238, 238, 210)
    dark = (118, 150, 86)
    accent = (129, 182, 76)
    ss = 3
    canvas = Canvas(size, (0, 0, 0))
    pad = 0 if maskable else size * 0.09
    tile = size - 2 * pad
    radius = 0 if maskable else size * 0.18
    board_size = tile * (0.72 if maskable else 0.92)
    board_x = (size - board_size) / 2
    board_y = board_x
    cell = board_size / 8
    # pawn silhouette geometry (relative to board)
    pc = (board_x + board_size / 2, board_y + board_size / 2)
    s = board_size
    head_r = s * 0.105
    head_y = pc[1] - s * 0.155
    body = [
        (pc[0] - s * 0.035, head_y + head_r * 0.55),
        (pc[0] + s * 0.035, head_y + head_r * 0.55),
        (pc[0] + s * 0.085, pc[1] + s * 0.105),
        (pc[0] - s * 0.085, pc[1] + s * 0.105),
    ]
    base = (pc[0] - s * 0.145, pc[1] + s * 0.105, s * 0.29, s * 0.075)
    for py in range(size):
        for px_ in range(size):
            r = g = b = 0
            for sy in range(ss):
                for sx in range(ss):
                    x = px_ + (sx + 0.5) / ss
                    y = py + (sy + 0.5) / ss
                    col = (0, 0, 0)
                    if maskable or rounded_rect(x - pad, y - pad, tile, tile, radius):
                        col = bg
                        # checkerboard, faded
                        bx = int((x - board_x) // cell)
                        by = int((y - board_y) // cell)
                        if 0 <= bx < 8 and 0 <= by < 8 and (bx + by) % 2 == 1:
                            if board_x <= x < board_x + board_size and board_y <= y < board_y + board_size:
                                col = (52, 49, 45)
                        # accent ring
                        d = ((x - pc[0]) ** 2 + (y - pc[1]) ** 2) ** 0.5
                        if abs(d - s * 0.40) < s * 0.008:
                            col = accent
                        # pawn
                        if (x - pc[0]) ** 2 + (y - head_y) ** 2 <= head_r * head_r:
                            col = light
                        elif in_poly(x, y, body):
                            col = light
                        elif rounded_rect(x - base[0], y - base[1], base[2], base[3], s * 0.02):
                            col = light
                    r += col[0]
                    g += col[1]
                    b += col[2]
            n = ss * ss
            canvas.set(px_, py, (r // n, g // n, b // n))
    return canvas


def build_icons():
    for size in (192, 256, 512):
        c = make_icon(size)
        c.save(os.path.join(ASSETS, "icon-%d.png" % size))
        m = make_icon(size, maskable=True)
        m.save(os.path.join(ASSETS, "icon-maskable-%d.png" % size))
    # apple touch icon
    make_icon(180).save(os.path.join(ASSETS, "apple-touch-icon.png"))
    build_ico()
    print("icons written")


def build_ico():
    """ICO с PNG-содержимым (256x256) для Windows-приложения."""
    png_path = os.path.join(ASSETS, "icon-256.png")
    with open(png_path, "rb") as fh:
        png = fh.read()
    header = struct.pack("<HHH", 0, 1, 1)
    entry = struct.pack("<BBBBHHII", 0, 0, 0, 0, 1, 32, len(png), 6 + 16)
    with open(os.path.join(ASSETS, "app.ico"), "wb") as fh:
        fh.write(header + entry + png)


if __name__ == "__main__":
    build_openings()
    build_pieces()
    build_icons()
